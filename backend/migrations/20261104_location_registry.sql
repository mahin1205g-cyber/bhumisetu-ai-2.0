-- Additive location registry for deed verification.
-- Additive migration; it does not rewrite existing location or deed data.
-- No existing location text, deed, property, or user rows are rewritten.

BEGIN;

CREATE TABLE IF NOT EXISTS location_dataset_imports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_key TEXT NOT NULL,
    source_url TEXT NOT NULL,
    dataset_version TEXT,
    retrieved_at DATE NOT NULL,
    sha256 CHAR(64) NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('pending', 'partial', 'complete', 'failed')),
    record_counts JSONB NOT NULL DEFAULT '{}'::jsonb,
    coverage_notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    imported_at TIMESTAMPTZ,
    UNIQUE (dataset_key, sha256)
);

CREATE TABLE IF NOT EXISTS divisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name_bn TEXT NOT NULL,
    name_en TEXT,
    source_import_id BIGINT REFERENCES location_dataset_imports(id) ON DELETE SET NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (BTRIM(code) <> ''),
    CHECK (BTRIM(name_bn) <> '')
);

CREATE TABLE IF NOT EXISTS districts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    division_id BIGINT NOT NULL REFERENCES divisions(id) ON DELETE RESTRICT,
    code TEXT NOT NULL,
    name_bn TEXT NOT NULL,
    name_en TEXT,
    source_import_id BIGINT REFERENCES location_dataset_imports(id) ON DELETE SET NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (division_id, code),
    CHECK (BTRIM(code) <> ''),
    CHECK (BTRIM(name_bn) <> '')
);

CREATE TABLE IF NOT EXISTS upazilas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district_id BIGINT NOT NULL REFERENCES districts(id) ON DELETE RESTRICT,
    code TEXT NOT NULL,
    name_bn TEXT NOT NULL,
    name_en TEXT,
    source_import_id BIGINT REFERENCES location_dataset_imports(id) ON DELETE SET NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (district_id, code),
    CHECK (BTRIM(code) <> ''),
    CHECK (BTRIM(name_bn) <> '')
);

CREATE TABLE IF NOT EXISTS police_thanas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district_id BIGINT NOT NULL REFERENCES districts(id) ON DELETE RESTRICT,
    code TEXT NOT NULL,
    name_bn TEXT NOT NULL,
    name_en TEXT,
    source_import_id BIGINT REFERENCES location_dataset_imports(id) ON DELETE SET NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (district_id, code),
    CHECK (BTRIM(code) <> ''),
    CHECK (BTRIM(name_bn) <> '')
);

CREATE TABLE IF NOT EXISTS mouzas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upazila_id BIGINT REFERENCES upazilas(id) ON DELETE RESTRICT,
    police_thana_id BIGINT REFERENCES police_thanas(id) ON DELETE RESTRICT,
    code TEXT NOT NULL,
    name_bn TEXT NOT NULL,
    name_en TEXT,
    source_reference TEXT NOT NULL,
    source_import_id BIGINT REFERENCES location_dataset_imports(id) ON DELETE SET NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK ((upazila_id IS NOT NULL) <> (police_thana_id IS NOT NULL)),
    CHECK (BTRIM(code) <> ''),
    CHECK (BTRIM(name_bn) <> ''),
    CHECK (BTRIM(source_reference) <> '')
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_mouzas_upazila_code
    ON mouzas (upazila_id, code) WHERE upazila_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_mouzas_thana_code
    ON mouzas (police_thana_id, code) WHERE police_thana_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_districts_division_active
    ON districts (division_id, is_active, name_bn);
CREATE INDEX IF NOT EXISTS idx_upazilas_district_active
    ON upazilas (district_id, is_active, name_bn);
CREATE INDEX IF NOT EXISTS idx_police_thanas_district_active
    ON police_thanas (district_id, is_active, name_bn);
CREATE INDEX IF NOT EXISTS idx_mouzas_upazila_active
    ON mouzas (upazila_id, is_active, name_bn);
CREATE INDEX IF NOT EXISTS idx_mouzas_thana_active
    ON mouzas (police_thana_id, is_active, name_bn);

ALTER TABLE deed_verifications
    ADD COLUMN IF NOT EXISTS district_id BIGINT REFERENCES districts(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS upazila_id BIGINT REFERENCES upazilas(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS police_thana_id BIGINT REFERENCES police_thanas(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS mouza_id BIGINT REFERENCES mouzas(id) ON DELETE SET NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'deed_verifications_location_type_check'
          AND conrelid = 'deed_verifications'::regclass
    ) THEN
        ALTER TABLE deed_verifications
            ADD CONSTRAINT deed_verifications_location_type_check
            CHECK (upazila_id IS NULL OR police_thana_id IS NULL);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_deed_verifications_district_id
    ON deed_verifications (district_id);
CREATE INDEX IF NOT EXISTS idx_deed_verifications_upazila_id
    ON deed_verifications (upazila_id);
CREATE INDEX IF NOT EXISTS idx_deed_verifications_police_thana_id
    ON deed_verifications (police_thana_id);
CREATE INDEX IF NOT EXISTS idx_deed_verifications_mouza_id
    ON deed_verifications (mouza_id);

COMMIT;
