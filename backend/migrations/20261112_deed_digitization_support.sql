-- Deed applications are kept separate from canonical deeds until staff approval.
-- This migration is prepared only; do not apply to production without backup,
-- restore rehearsal, rollback plan, and explicit production approval.
BEGIN;

CREATE TABLE deed_digitization_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_year INTEGER NOT NULL DEFAULT EXTRACT(YEAR FROM NOW())::INTEGER,
    tracking_id TEXT GENERATED ALWAYS AS (
        'BHM-DIG-' || tracking_year::TEXT || '-' || LPAD(id::TEXT, GREATEST(6, LENGTH(id::TEXT)), '0')
    ) STORED UNIQUE,
    owner_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    assigned_officer_id INTEGER REFERENCES users(id) ON DELETE RESTRICT,
    status TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN (
        'submitted', 'under_review', 'correction_required', 'resubmitted',
        'approved', 'digitization_processing', 'completed', 'rejected', 'cancelled'
    )),
    entry_method TEXT NOT NULL CHECK (entry_method IN ('ocr', 'manual')),
    deed_data JSONB NOT NULL,
    ocr_text TEXT NOT NULL DEFAULT '',
    ai_extraction_used BOOLEAN NOT NULL DEFAULT FALSE,
    finalized_deed_id INTEGER REFERENCES deeds(id) ON DELETE RESTRICT,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK ((status = 'completed' AND finalized_deed_id IS NOT NULL) OR status <> 'completed')
);

CREATE INDEX idx_deed_applications_owner_submitted
    ON deed_digitization_applications(owner_user_id, submitted_at DESC, id DESC);
CREATE INDEX idx_deed_applications_queue
    ON deed_digitization_applications(status, submitted_at, id);
CREATE INDEX idx_deed_applications_assigned_queue
    ON deed_digitization_applications(assigned_officer_id, status, submitted_at, id)
    WHERE assigned_officer_id IS NOT NULL;
CREATE INDEX idx_deed_applications_tracking
    ON deed_digitization_applications(tracking_id);
CREATE INDEX idx_deed_applications_data_gin
    ON deed_digitization_applications USING GIN(deed_data jsonb_path_ops);

CREATE TABLE deed_digitization_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES deed_digitization_applications(id) ON DELETE RESTRICT,
    actor_user_id INTEGER REFERENCES users(id) ON DELETE RESTRICT,
    actor_role TEXT NOT NULL,
    from_status TEXT,
    to_status TEXT NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_deed_digitization_history_app
    ON deed_digitization_status_history(application_id, id);

CREATE TABLE deed_digitization_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES deed_digitization_applications(id) ON DELETE RESTRICT,
    uploaded_by INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    original_filename TEXT NOT NULL,
    content_type TEXT NOT NULL,
    byte_length BIGINT NOT NULL CHECK (byte_length > 0),
    storage_path TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_deed_digitization_documents_app
    ON deed_digitization_documents(application_id, id);

-- Metadata extends the existing deeds row only after approval; there is no
-- duplicate deeds table. Unique application_id makes approval retry-safe.
CREATE TABLE deed_digitization_metadata (
    deed_id INTEGER PRIMARY KEY REFERENCES deeds(id) ON DELETE RESTRICT,
    application_id BIGINT NOT NULL UNIQUE REFERENCES deed_digitization_applications(id) ON DELETE RESTRICT,
    owner_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    entry_method TEXT NOT NULL CHECK (entry_method IN ('ocr', 'manual')),
    review_status TEXT NOT NULL DEFAULT 'reviewed' CHECK (review_status IN ('reviewed')),
    is_archived BOOLEAN NOT NULL DEFAULT FALSE,
    original_document_path TEXT,
    generated_pdf_path TEXT,
    ai_extraction_used BOOLEAN NOT NULL DEFAULT FALSE,
    supplemental_fields JSONB NOT NULL DEFAULT '{}'::jsonb,
    additional_parties JSONB NOT NULL DEFAULT '[]'::jsonb,
    additional_parcels JSONB NOT NULL DEFAULT '[]'::jsonb,
    digital_deed_id TEXT NOT NULL UNIQUE,
    verification_token TEXT NOT NULL UNIQUE,
    verification_token_hash TEXT NOT NULL UNIQUE,
    record_status TEXT NOT NULL DEFAULT 'active' CHECK (record_status IN ('active', 'revoked')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_deed_digitization_owner_created
    ON deed_digitization_metadata(owner_user_id, created_at DESC, deed_id DESC);
CREATE INDEX idx_deed_digitization_status
    ON deed_digitization_metadata(record_status, created_at DESC);
CREATE INDEX idx_deed_digitization_parties
    ON deed_digitization_metadata USING GIN(additional_parties jsonb_path_ops);
CREATE INDEX idx_deed_digitization_parcels
    ON deed_digitization_metadata USING GIN(additional_parcels jsonb_path_ops);

COMMIT;
