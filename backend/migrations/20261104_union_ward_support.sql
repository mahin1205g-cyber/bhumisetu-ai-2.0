-- Add official Union suggestions and optional typed Union/Ward verification text.
BEGIN;

CREATE TABLE IF NOT EXISTS admin_unions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    upazila_id BIGINT REFERENCES upazilas(id) ON DELETE SET NULL,
    name_bn TEXT NOT NULL,
    name_en TEXT,
    parent_upazila_name_bn TEXT,
    parent_upazila_name_en TEXT NOT NULL,
    parent_district_name_en TEXT NOT NULL,
    source_import_id BIGINT REFERENCES location_dataset_imports(id) ON DELETE SET NULL,
    source_reference TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (BTRIM(code) <> ''),
    CHECK (BTRIM(name_bn) <> ''),
    CHECK (BTRIM(parent_upazila_name_en) <> ''),
    CHECK (BTRIM(parent_district_name_en) <> ''),
    CHECK (BTRIM(source_reference) <> '')
);

CREATE INDEX IF NOT EXISTS idx_admin_unions_upazila_active
    ON admin_unions (upazila_id, is_active, name_bn);

ALTER TABLE deed_verifications
    ADD COLUMN IF NOT EXISTS union_id BIGINT REFERENCES admin_unions(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS union_ward TEXT;

CREATE INDEX IF NOT EXISTS idx_deed_verifications_union_id
    ON deed_verifications (union_id);

COMMIT;
